#!/usr/bin/env python3
"""把 src/web/index.html 内嵌成 C 头文件（免 SPIFFS/文件系统，直接烧进 flash）。

用法： python tools/html_to_c.py [输入html] [输出头文件]
默认： src/web/index.html -> src/app/index_html.h
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "web", "index.html")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "src", "app", "index_html.h")

DELIM = "HTMLRAW_END"

html = open(SRC, "r", encoding="utf-8").read()
if DELIM in html:
    print("错误：HTML 里出现了保留分隔符 %s" % DELIM)
    sys.exit(1)

header = (
    "/* AUTO-GENERATED by tools/html_to_c.py — DO NOT EDIT. 编辑 src/web/index.html 后重跑。 */\n"
    "#pragma once\n\n"
    "const char INDEX_HTML[] =\n"
    "R\"%s(\n%s\n)%s\";\n" % (DELIM, html, DELIM)
)

open(OUT, "w", encoding="utf-8", newline="\n").write(header)
print("生成 %s（%d 字节 HTML）" % (os.path.relpath(OUT, ROOT), len(html.encode("utf-8"))))
